-- ADR-0003 (#152): шифротекст блока хранится как непрозрачный текст, ключ сейфа задаёт клиент.
-- Совместимо в обе стороны: прежняя версия API по-прежнему может создавать сейфы (колонка стала необязательной).

ALTER TABLE "block" ADD COLUMN "ciphertext" TEXT;

ALTER TABLE "vault" ALTER COLUMN "mk_wrapped" DROP NOT NULL;

-- Прежний сервер генерировал mk_wrapped сам (случайные байты, открытым текстом): это не конверт v1
-- и ничего не защищает. Такие значения обнуляются: ключ нужно настроить из браузера владельца.
-- Если прежний API успеет вставить такое значение уже после миграции (обновление без остановки), новый код всё равно
-- считает сейф ненастроенным: «ключ настроен» значит валидный конверт v1, а PUT /vaults/:id/key заменяет и такое значение.
UPDATE "vault"
SET "mk_wrapped" = NULL
WHERE "mk_wrapped" !~ '^v1\.[A-Za-z0-9_-]{16}\.[A-Za-z0-9_-]{64}$';
